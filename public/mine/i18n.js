  const isLang = (v) => typeof v === 'string' && SUPPORTED.indexOf(v) !== -1;

  function fromQuery() {
    try {
      const v = new URLSearchParams(window.location.search).get('lang');
      return isLang(v) ? v : null;
    } catch (_e) { return null; }
  }

  function fromStorage() {
    try {
      const v = window.localStorage.getItem(STORAGE_KEY);
      return isLang(v) ? v : null;
    } catch (_e) { return null; }
  }

  function fromTelegram() {
    const tg = window.Telegram && window.Telegram.WebApp;
    const code = String((tg && tg.initDataUnsafe && tg.initDataUnsafe.user && tg.initDataUnsafe.user.language_code) || '')
      .toLowerCase()
      .slice(0, 2);
    return isLang(code) ? code : null;
  }

  function detect() {
    return fromQuery() || fromStorage() || fromTelegram() || 'uz';
  }

  let lang = detect();

  function t(key, vars) {
    const cur = DICT[lang];
    let s = (cur && cur[key]) || DICT.uz[key] || key;
    if (vars) for (const k of Object.keys(vars)) s = s.split('{' + k + '}').join(String(vars[k]));
    return s;
  }

  function has(key) { return Object.prototype.hasOwnProperty.call(DICT.uz, key); }

  function parseVars(raw) {
    if (!raw) return undefined;
    try { return JSON.parse(raw); } catch (_e) { return undefined; }
  }

  function apply(root) {
    const scope = root || document;
    scope.querySelectorAll('[data-i18n]').forEach((n) => { n.textContent = t(n.dataset.i18n, parseVars(n.dataset.i18nVars)); });
    scope.querySelectorAll('[data-i18n-placeholder]').forEach((n) => { n.setAttribute('placeholder', t(n.dataset.i18nPlaceholder)); });
    scope.querySelectorAll('[data-i18n-title]').forEach((n) => { n.setAttribute('title', t(n.dataset.i18nTitle)); });
    scope.querySelectorAll('[data-i18n-aria]').forEach((n) => { n.setAttribute('aria-label', t(n.dataset.i18nAria)); });
    scope.querySelectorAll('[data-i18n-alt]').forEach((n) => { n.setAttribute('alt', t(n.dataset.i18nAlt)); });
  }

  /** Tilni almashtiradi. Noto'g'ri qiymat rad etiladi (false). Til haqiqatan o'zgargan bo'lsa hodisa yuboriladi. */
  function setLang(next) {
    if (!isLang(next)) return false;
    try { window.localStorage.setItem(STORAGE_KEY, next); } catch (_e) { /* private rejim */ }
    if (next === lang) return true;
    const prev = lang;
    lang = next;
    document.documentElement.lang = lang;
    apply();
    try {
      window.dispatchEvent(new CustomEvent('adrush:langchange', { detail: { lang, prev } }));
    } catch (_e) { /* eski brauzer */ }
    return true;
  }

  document.documentElement.lang = lang;
  window.AdRushI18n = {
    t,
    has,
    apply,
    setLang,
    detect,
    supported: SUPPORTED.slice(),
    get lang() { return lang; },
    get locale() { return LOCALES[lang]; },
  };
  if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', () => apply());
  else apply();
